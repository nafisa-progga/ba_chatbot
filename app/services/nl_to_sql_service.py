# app/services/nl_to_sql_service.py

from langchain_google_genai import ChatGoogleGenerativeAI
from langchain.prompts import PromptTemplate
from langchain.chains import LLMChain
import oracledb
from app.database.oracle_connector import get_db_connection

# Use the pre-configured Google AI model for generating the SQL query
llm_sql_generator = ChatGoogleGenerativeAI(model="gemini-2.5-flash-preview-05-20", temperature=0.2)

# Use a separate LLM for generating the final conversational response
llm_response_generator = ChatGoogleGenerativeAI(model="gemini-2.5-flash-preview-05-20", temperature=0.2)


# Define the prompt template for converting natural language to SQL
SQL_PROMPT_TEMPLATE = """
You are a Oracle SQL expert. Your task is to convert a natural language question into a syntactically correct Oracle SQL query.
Do not include a semicolon (;) at the end of the query.

Use the following table schemas to assist you:
Table: employees
Columns: id (INTEGER), name (VARCHAR2), department (VARCHAR2), salary (INTEGER)

Table: products
Columns: product_id (INTEGER), product_name (VARCHAR2), price (NUMBER), stock_quantity (INTEGER)

Question: {question}

SQL Query:
"""

# Define a new prompt template for generating the final conversational response
RESPONSE_PROMPT_TEMPLATE = """
You are a helpful and friendly AI assistant.
Your task is to create a concise, conversational natural language statement based on the provided raw query results.
The response should be small and user-friendly, no more than 3 lines.

Original user query: {original_question}
Query results (raw data): {results_string}

Please craft a single, short, conversational sentence or two that summarizes the data.
"""

def get_sql_query_and_execute(question: str) -> str:
    """
    Generates a SQL query, executes it against the Oracle database,
    and returns a formatted string with the results.
    """
    # 1. GENERATE THE SQL QUERY
    prompt_sql = PromptTemplate(
        input_variables=["question"],
        template=SQL_PROMPT_TEMPLATE
    )
    
    chain_sql = LLMChain(llm=llm_sql_generator, prompt=prompt_sql)
    
    # Run the chain to get the generated SQL query
    generated_sql = chain_sql.run(question=question)
    # The generated query might contain extra text, so we clean it up
    cleaned_sql = generated_sql.strip().replace("```sql", "").replace("```", "").strip()

    print(f"Generated SQL Query: {cleaned_sql}")
    
    # 2. EXECUTE THE QUERY AGAINST THE DATABASE
    connection = None
    try:
        connection = get_db_connection()
        cursor = connection.cursor()
        
        # Execute the generated SQL query
        cursor.execute(cleaned_sql)
        
        # Fetch all results from the query
        results = cursor.fetchall()

        # Get column names for formatting
        columns = [col[0] for col in cursor.description]
        
        # 3. CONVERT RESULTS INTO A CONVERSATIONAL RESPONSE USING AN LLM
        if not results:
            return "No data found for this query."
            
        # Format the raw results into a string to pass to the LLM
        results_string = f"Columns: {', '.join(columns)}\nRows: {results}"
        
        # Create a new chain for the final conversational response
        prompt_response = PromptTemplate(
            input_variables=["original_question", "results_string"],
            template=RESPONSE_PROMPT_TEMPLATE
        )
        chain_response = LLMChain(llm=llm_response_generator, prompt=prompt_response)
        
        # Run the chain to get the final conversational answer
        final_answer = chain_response.run(
            original_question=question,
            results_string=results_string
        )

        # Return the LLM's final response
        return final_answer
        
    except oracledb.Error as e:
        # Handle errors during query execution (e.g., LLM generated a bad query)
        error, = e.args
        print(f"Database Error: {error.message}")
        return f"An error occurred while executing the query. Please check the SQL generated by the model.\nError: {error.message}"
        
    finally:
        if connection:
            connection.close()
            print("Database connection closed.")


# This function remains a wrapper for the main function
def get_sql_query(question: str) -> str:
    return get_sql_query_and_execute(question)
